"""Build the tutorial.ipynb deterministically from this script.

Run with:
  python examples/build_tutorial_nb.py
  jupyter nbconvert --execute examples/tutorial.ipynb --to notebook --inplace
"""

from pathlib import Path

import nbformat as nbf

HERE = Path(__file__).resolve().parent
OUT = HERE / "tutorial.ipynb"

nb = nbf.v4.new_notebook()
cells = [
    nbf.v4.new_markdown_cell(
        "# `awe-agent-function` — tutorial\n\n"
        "Five steps to make a Python package agent-friendly:\n\n"
        "1. Install the package: `pip install -e .` (from the repo root).\n"
        "2. Decorate one function by hand and inspect the registry.\n"
        "3. Auto-decorate a foreign package (sklearn) without modifying its source.\n"
        "4. Audit the resulting registry against the AFS rubric.\n"
        "5. Visualise the AFS distribution and compare omicverse vs sklearn.\n\n"
        "All output cells below were generated by re-executing the\n"
        "notebook end-to-end."
    ),

    nbf.v4.new_markdown_cell(
        "## Step 1 · Decorate by hand\n\n"
        "The decorator is the only authoring surface. Everything else\n"
        "(registry, lookup, AFS audit) is derived from what you wrote\n"
        "at the call site."
    ),
    nbf.v4.new_code_cell(
        "import warnings\n"
        "warnings.filterwarnings('ignore')\n"
        "from awe_agent_function import register_function, registry_lookup, registry_summary\n"
        "\n"
        "@register_function(\n"
        "    aliases=['zscore', 'standard score', 'z-score', '标准化'],\n"
        "    category='preprocessing',\n"
        "    description='Convert a 1-D numeric array to its z-score (zero mean, unit variance).',\n"
        "    requires={'shape': ['1d_array']},\n"
        "    produces={'shape': ['1d_array'], 'metrics': ['mean=0', 'std=1']},\n"
        "    examples=['zscore([1, 2, 3, 4, 5])  # array([-1.41, -0.71, 0.0, 0.71, 1.41])'],\n"
        "    related=['minmax_scale', 'robust_scale'],\n"
        ")\n"
        "def zscore(x):\n"
        "    import numpy as np\n"
        "    x = np.asarray(x, dtype=float)\n"
        "    sd = x.std(ddof=0)\n"
        "    return (x - x.mean()) / (sd if sd else 1.0)\n"
        "\n"
        "print(registry_lookup('z-score'))"
    ),

    nbf.v4.new_markdown_cell(
        "## Step 2 · Auto-decorate sklearn (no source mod)\n\n"
        "The same registry surface, applied to a package the framework\n"
        "authors do not own. `auto_decorate` walks sklearn's public API,\n"
        "AST-extracts each callable's signature + docstring, and\n"
        "synthesises a registry entry per public function / class."
    ),
    nbf.v4.new_code_cell(
        "from awe_agent_function import auto_decorate\n"
        "n = auto_decorate('sklearn', recurse_depth=2)\n"
        "print(f'registered {n} sklearn entries')"
    ),

    nbf.v4.new_markdown_cell(
        "## Step 3 · Natural-language lookup\n\n"
        "The agent (or you) queries the registry with a phrase that\n"
        "describes the analytical decision, not the function name. The\n"
        "lookup returns full name, AST-derived signature, examples, and\n"
        "the 'See Also' list for further navigation."
    ),
    nbf.v4.new_code_cell(
        "for q in [\n"
        "    'random forest classifier',\n"
        "    'feature selection wrapper',\n"
        "    'silhouette score for clustering',\n"
        "    'stratified k-fold cross validation',\n"
        "]:\n"
        "    print('=' * 72)\n"
        "    print(f'registry_lookup({q!r}):')\n"
        "    print('=' * 72)\n"
        "    print(registry_lookup(q, max_results=2))\n"
        "    print()"
    ),

    nbf.v4.new_markdown_cell(
        "## Step 4 · AFS audit\n\n"
        "Quantitatively grade the library against the four-dimension\n"
        "rubric (Discoverability, Contract, Signature, Behaviour).\n"
        "The summary tells you the library-level score and the per-\n"
        "component means; the per-row table tells you which functions\n"
        "to enrich next."
    ),
    nbf.v4.new_code_cell(
        "from awe_agent_function import compute_afs\n"
        "rep = compute_afs(library_name='sklearn')\n"
        "print(rep.summary())"
    ),

    nbf.v4.new_markdown_cell(
        "## Step 5 · Visualise the AFS distribution\n\n"
        "The histogram shows the per-function score distribution; the\n"
        "bar chart shows where in the rubric the library has the most\n"
        "headroom. For sklearn the contract dimension is at zero by\n"
        "construction — `requires` / `produces` cannot be synthesised\n"
        "from a docstring alone, only authored. That is the difference\n"
        "between auto-decoration (cheap, library-agnostic, partial)\n"
        "and call-site decoration (one-time author cost, full A3F)."
    ),
    nbf.v4.new_code_cell(
        "import matplotlib.pyplot as plt\n"
        "import numpy as np\n"
        "\n"
        "afs_vals = [r['AFS'] for r in rep.rows]\n"
        "ss = rep.subscore_means\n"
        "weights = rep.weights\n"
        "\n"
        "fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9, 3.2),\n"
        "                                gridspec_kw={'width_ratios': [1.4, 1.0]})\n"
        "ax1.hist(afs_vals, bins=20, color='#1f4f8c', edgecolor='white', linewidth=0.4)\n"
        "ax1.axvline(rep.library_afs_mean, color='#cc7a3a', linestyle='--',\n"
        "            label=f'mean = {rep.library_afs_mean:.2f}')\n"
        "ax1.axvline(rep.library_afs_median, color='black', linestyle=':',\n"
        "            label=f'median = {rep.library_afs_median:.2f}')\n"
        "ax1.set_xlabel('AFS')\n"
        "ax1.set_ylabel('# functions')\n"
        "ax1.set_xlim(0, 1)\n"
        "ax1.legend(loc='upper left', frameon=False)\n"
        "ax1.set_title(f'(a) sklearn AFS distribution (n={rep.n_functions})')\n"
        "ax1.grid(axis='y', linestyle=':', alpha=0.5)\n"
        "for sp in ('top','right'): ax1.spines[sp].set_visible(False)\n"
        "\n"
        "labels = ['Discoverability\\n(D)', 'Contract\\n(C)', 'Signature\\n(S)', 'Behaviour\\n(B)']\n"
        "vals = [ss['D'], ss['C'], ss['S'], ss['B']]\n"
        "ws = [weights['D'], weights['C'], weights['S'], weights['B']]\n"
        "x = np.arange(len(labels))\n"
        "ax2.bar(x, vals, color='#1f4f8c', edgecolor='white', linewidth=0.4)\n"
        "for xi, v in enumerate(vals):\n"
        "    ax2.text(xi, v + 0.02, f'{v:.2f}', ha='center', fontsize=8)\n"
        "for xi, w in enumerate(ws):\n"
        "    ax2.text(xi, -0.07, f'w={w:.2f}', ha='center', fontsize=7,\n"
        "             color='gray', transform=ax2.get_xaxis_transform())\n"
        "ax2.set_xticks(x); ax2.set_xticklabels(labels, fontsize=8)\n"
        "ax2.set_ylim(0, 1.0)\n"
        "ax2.set_ylabel('mean sub-score')\n"
        "ax2.set_title('(b) AFS components')\n"
        "ax2.grid(axis='y', linestyle=':', alpha=0.5)\n"
        "for sp in ('top','right'): ax2.spines[sp].set_visible(False)\n"
        "\n"
        "fig.tight_layout()\n"
        "plt.show()"
    ),

    nbf.v4.new_markdown_cell(
        "## What's next\n\n"
        "- Drop `awe-agent-function` into your own library and add\n"
        "  `@register_function` at each public-API call site (≈ 4–5\n"
        "  declarative lines per function).\n"
        "- Run `compute_afs(library_name='your_pkg')` and prioritise\n"
        "  the lowest-scoring entries.\n"
        "- For multi-step recipes, ship Markdown skills under\n"
        "  `.claude/skills/<slug>/SKILL.md`. The 12-principle content\n"
        "  contract and 9-dimension rubric are at\n"
        "  https://github.com/aristoteleo/awesome-skill-generate ."
    ),
]
nb["cells"] = cells
OUT.write_text(nbf.writes(nb))
print("wrote", OUT.name)
